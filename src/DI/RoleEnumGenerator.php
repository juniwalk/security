namespace JuniWalk\Security\DI;

use InvalidArgumentException;
use JuniWalk\Security\Definitions;
use Nette\PhpGenerator\EnumType;
use Nette\PhpGenerator\PhpFile;
use JuniWalk\Utils\Enums\Color;
use JuniWalk\Utils\Enums\Interfaces\LabeledEnum;
use JuniWalk\Utils\Enums\Interfaces\PoweredRole;
use JuniWalk\Utils\Enums\Traits\Labeled;
use JuniWalk\Utils\Format;
use JuniWalk\Security\Provider;
use Nette\Utils\FileSystem;
use Nette\Utils\Strings;

use function file_get_contents;
use function is_file;
use function preg_match;
use function rtrim;
use function strrpos;
use function substr;

/**
 * Generates backed enum with a case for every role of the definitions.
 */
final class RoleEnumGenerator
{
	/**
	 * Writes the enum file when its content changed and returns the file path.
	 */
	public function write(string $class, string $directory, Definitions $definitions): string
	{
		$file = $this->path($class, $directory);
		$code = $this->generate($class, $definitions);

		if (!is_file($file) || file_get_contents($file) !== $code) {
			FileSystem::write($file, $code);
		}

		return $file;
	}


	/**
	 * Recreates the enum file when it is missing, e.g. after the cache was cleared, and loads it.
	 */
	public static function load(string $class, string $directory, Provider $provider): void
	{
		$generator = new self;
		$file = $generator->path($class, $directory);

		if (!is_file($file)) {
			$generator->write($class, $directory, $provider->load());
		}

		require_once $file;
	}


	public function path(string $class, string $directory): string
	{
		return rtrim($directory, '/\\').'/'.$this->shortName($class).'.php';
	}


	public function generate(string $class, Definitions $definitions): string
	{
		$namespace = ($pos = strrpos($class, '\\')) !== false ? substr($class, 0, $pos) : '';
		$enum = new EnumType($this->shortName($class), $namespace === '' ? null : (new PhpFile)->addNamespace($namespace));
		$enum->setType('string');
		$enum->addImplement(LabeledEnum::class);
		$enum->addImplement(PoweredRole::class);
		$enum->addTrait(Labeled::class);
		$enum->addComment('Generated by JuniWalk\Security\DI\PermissionExtension, do not edit.');

		$cases = [];
		$parents = [];
		$labels = [];
		$colors = [];
		$powers = [];

		foreach ($definitions->roles as $role) {
			$case = self::toPascalCase($role->name);

			if (isset($cases[$case])) {
				throw new InvalidArgumentException('Roles "'.$cases[$case].'" and "'.$role->name.'" collide in enum case "'.$case.'" of '.$class.'.');
			}

			$cases[$case] = $role->name;
			$enum->addCase($case, $role->name);
			$parents[$role->name] = $role->parents ?: null;
			$labels[$case] = $role->getLabel();
			$colors[$case] = $role->color;
			$powers[$case] = $role->power;
		}

		$enum->addMethod('getMap')
			->setStatic()
			->setReturnType('array')
			->addComment('@return array<string, string[]|null> Role parents by role name')
			->setBody('return '.$this->export($parents).';');

		$enum->addMethod('label')
			->setReturnType('string')
			->setBody("return match (\$this) {\n".$this->arms($labels)."};");

		$enum->addMethod('color')
			->setReturnType(Color::class)
			->setBody("return match (\$this) {\n".$this->colorArms($colors)."};");

		$enum->addMethod('power')
			->setReturnType('int')
			->setBody("return match (\$this) {\n".$this->arms($powers)."};");

		$enum->addMethod('hasPowerOver')
			->setReturnType('bool')
			->setBody('return $this->power() >= $role->power();')
			->addParameter('role')->setType(PoweredRole::class);

		$enum->addMethod('getRoleId')
			->setReturnType('string')
			->setBody('return $this->value;');

		$file = new PhpFile;
		$file->setStrictTypes();
		$target = $namespace === '' ? $file->addNamespace('') : $file->addNamespace($namespace);
		$target->add($enum);

		return (string) $file;
	}


	/**
	 * @param array<string, string|int> $values by case name
	 */
	private function arms(array $values): string
	{
		$code = '';

		foreach ($values as $case => $value) {
			$code .= "\tself::$case => ".$this->export($value).",\n";
		}

		return $code;
	}


	/**
	 * @param array<string, string|null> $colors by case name
	 */
	private function colorArms(array $colors): string
	{
		$code = '';

		foreach ($colors as $case => $color) {
			$value = Color::tryFrom((string) $color) ?? Color::Secondary;
			$code .= "\tself::$case => \\".Color::class.'::'.$value->name.",\n";
		}

		return $code;
	}


	private function export(mixed $value): string
	{
		return (new \Nette\PhpGenerator\Dumper)->dump($value);
	}


	private function shortName(string $class): string
	{
		return ($pos = strrpos($class, '\\')) !== false ? substr($class, $pos + 1) : $class;
	}


	/**
	 * Valid PascalCase identifier, webalize turns dots, spaces and diacritics into dashes or ASCII, the case is kept.
	 */
	public static function toPascalCase(string $value): string
	{
		$name = Format::pascalCase(Strings::webalize($value, null, false));

		if ($name === '' || preg_match('/^\d/', $name)) {
			throw new InvalidArgumentException('Value "'.$value.'" cannot be converted to a valid name, use a different one or name the enum explicitly.');
		}

		return $name;
	}
}
